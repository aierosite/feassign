"""Emit test-only Fe cases by exact injections, without Hungarian/JV/search.
Matrices use little-endian base-N digits in row-major order."""
from pathlib import Path
import hashlib
import itertools
import json
import math

ROOT = Path(__file__).resolve().parents[1]
SPACES = [
    ('ternary_1x1', 1, 1, [-1, 0, 1]),
    ('ternary_1x2', 1, 2, [-1, 0, 1]),
    ('ternary_1x3', 1, 3, [-1, 0, 1]),
    ('ternary_1x4', 1, 4, [-1, 0, 1]),
    ('ternary_2x2', 2, 2, [-1, 0, 1]),
    ('ternary_2x3', 2, 3, [-1, 0, 1]),
    ('binary_3x3', 3, 3, [0, 1]),
    ('endpoints_2x2', 2, 2, [-(2**63), 0, 2**63 - 1]),
    ('endpoints_2x3', 2, 3, [-(2**63), 0, 2**63 - 1]),
]


def matrix_for(ordinal, cells, alphabet):
    values = []
    for _ in range(cells):
        values.append(alphabet[ordinal % len(alphabet)])
        ordinal //= len(alphabet)
    return values


def exact_minimum(costs, rows, columns):
    return min(sum(costs[row * columns + col] for row, col in enumerate(injection))
               for injection in itertools.permutations(range(columns), rows))


def main():
    text = '''// Generated by tools/generate-oracle.py after the contest opening.
// Expected costs are Python exhaustive injection minima, never a Hungarian port.
use core::Result
use assignment::{new_problem, solve, verify}

fn oracle_check(_ r: u8, _ c: u8, _ costs: ref [i64; 1024], _ expected: i128, _ ordinal: usize) {
    let problem = match new_problem(r, c, (r as u16) * (c as u16), costs) {
        Result::Ok(value) => value,
        Result::Err(_) => core::panic_with_value(ordinal as u256),
    }
    let certificate = match solve(ref problem) {
        Result::Ok(value) => value,
        Result::Err(_) => core::panic_with_value(ordinal as u256),
    }
    match verify(ref problem, ref certificate) {
        Result::Ok(total) => {
            if total != expected { core::panic_with_value(ordinal as u256) }
        }
        Result::Err(_) => core::panic_with_value(ordinal as u256),
    }
}
'''
    spaces = []
    for name, rows, columns, alphabet in SPACES:
        count = len(alphabet) ** (rows * columns)
        expected = [exact_minimum(matrix_for(i, rows * columns, alphabet), rows, columns)
                    for i in range(count)]
        table = '\n'.join('        ' + ', '.join(map(str, expected[i:i+8])) + ','
                          for i in range(0, count, 8))
        text += f'''
#[test]
fn oracle_{name}() {{
    let alphabet: [i64; {len(alphabet)}] = [{', '.join(map(str, alphabet))}]
    let expected: [i128; {count}] = [
{table}
    ]
    var costs: [i64; 1024] = [0; 1024]
    var ordinal: usize = 0
    while ordinal < {count} {{
        var digits = ordinal
        var cell: usize = 0
        while cell < {rows * columns} {{
            costs[cell] = alphabet[digits % {len(alphabet)}]
            digits /= {len(alphabet)}
            cell += 1
        }}
        oracle_check({rows}, {columns}, ref costs, expected[ordinal], ordinal)
        ordinal += 1
    }}
}}
'''
        spaces.append(dict(name=name, rows=rows, columns=columns, alphabet=alphabet,
                           matrices=count, injections_per_matrix=math.perm(columns, rows),
                           expected_minima=expected))
    shape_families = []
    for first_column in range(1, 33, 4):
        last_column = first_column + 3
        expected = []
        shapes = []
        for columns in range(first_column, last_column + 1):
            column_offsets = [(j * 17) % 37 - 18 for j in range(columns)]
            for rows in range(1, columns + 1):
                # C[i,j]=a[i]+b[j]: every injection uses all a and r distinct b.
                # The optimum is therefore sum(a)+sum(r smallest b), not a
                # Hungarian implementation and not exhaustive general32 proof.
                optimum = sum(i * 13 - 200 for i in range(rows)) + sum(sorted(column_offsets)[:rows])
                expected.append(optimum)
                shapes.append(dict(rows=rows, columns=columns, expected=optimum))
        table = '\n'.join('        ' + ', '.join(map(str, expected[i:i+8])) + ','
                          for i in range(0, len(expected), 8))
        name = f'separable_shapes_columns_{first_column}_{last_column}'
        text += f'''
#[test]
fn oracle_{name}() {{
    let expected: [i128; {len(expected)}] = [
{table}
    ]
    var costs: [i64; 1024] = [0; 1024]
    var ordinal: usize = 0
    var columns: u8 = {first_column}
    while columns <= {last_column} {{
        var rows: u8 = 1
        while rows <= columns {{
            var i: usize = 0
            while i < (rows as usize) {{
                let row_index: i64 = i.downcast().unwrap()
                var j: usize = 0
                while j < (columns as usize) {{
                    let column_offset: i64 = ((j * 17) % 37).downcast().unwrap()
                    costs[i * (columns as usize) + j] = row_index * 13 - 200 + column_offset - 18
                    j += 1
                }}
                i += 1
            }}
            oracle_check(rows, columns, ref costs, expected[ordinal], ordinal)
            ordinal += 1
            rows += 1
        }}
        columns += 1
    }}
    assert!(ordinal == {len(expected)})
}}
'''
        shape_families.append(dict(name=name, first_column=first_column, last_column=last_column,
                                   matrices=len(shapes), shapes=shapes,
                                   formula='C[i,j]=(13*i-200)+((17*j)%37-18)',
                                   expected_from='sum(row offsets)+sum(rows smallest column offsets)'))
    output = ROOT / 'ingots/api_tests/src/oracle.fe'
    data = text.encode('utf-8')
    output.write_bytes(data)
    manifest = dict(classification='Independent finite-space expected costs; execution evidence is separate',
                    generation='Little-endian base-N digits, logical row-major matrix',
                    oracle='Python arbitrary-precision exhaustive distinct-column injections; not Hungarian/JV',
                    spaces=spaces, shape_families=shape_families,
                    exhaustive_space_matrices=sum(x['matrices'] for x in spaces),
                    closed_form_shape_matrices=sum(x['matrices'] for x in shape_families),
                    matrices=sum(x['matrices'] for x in spaces) + sum(x['matrices'] for x in shape_families),
                    enumerated_injections=sum(x['matrices'] * x['injections_per_matrix'] for x in spaces),
                    generated_fe='ingots/api_tests/src/oracle.fe',
                    generated_fe_sha256=hashlib.sha256(data).hexdigest(),
                    generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                    tests_executed_by_generation=False,
                    scope_limit='Exhaustive only in listed small finite spaces. The528-shape separable family has closed-form optima; it is not exhaustive over general i64 matrices.')
    (ROOT / 'docs/evidence/oracle-cases.json').write_bytes(
        (json.dumps(manifest, indent=2) + '\n').encode('utf-8'))
    print(json.dumps({key: manifest[key] for key in
                      ['matrices', 'enumerated_injections', 'generated_fe', 'generated_fe_sha256',
                       'tests_executed_by_generation']}))


if __name__ == '__main__':
    main()
